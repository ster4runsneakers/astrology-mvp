def warm_wrap(section_title: str, body: str) -> str:
    body = (body or "").strip()
    if not body:
        return body
    leads = {
        "Ήλιος": "Όταν ανάβουν τα φώτα πάνω σου — ο Ήλιος:",
        "Σελήνη": "Κι όταν μένεις μόνος με τον εαυτό σου — η Σελήνη:",
        "Ωροσκόπος": "Η πρώτη εντύπωση που αφήνεις — ο Ωροσκόπος:",
        "Ερμής": "Πώς σκέφτεσαι και μιλάς — ο Ερμής:",
        "Αφροδίτη": "Πώς αγαπάς και τι σε μαγεύει — η Αφροδίτη:",
        "Άρης": "Πώς διεκδικείς και θυμώνεις — ο Άρης:",
    }
    lead = "Άκου προσεκτικά:"
    for k, v in leads.items():
        if k in section_title:
            lead = v
            break
    for old in (
        "Κοίτα τον Ήλιο σου λίγο πιο βαθιά:",
        "Κι η Σελήνη; Εδώ χτυπάει η καρδιά:",
        "Κι αυτό που δείχνεις στον κόσμο;",
        "Στον τρόπο που μιλάς και σκέφτεσαι,",
        "Στην αγάπη και σε ό,τι σε μαγεύει,",
        "Στην ώθηση και στη σύγκρουση,",
        "Άκου αυτό:",
    ):
        if body.startswith(old):
            body = body[len(old) :].strip()
    return f"**{lead}** {body}"
