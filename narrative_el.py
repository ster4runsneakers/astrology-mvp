def _trap(sun: ZodiacSignId, moon: ZodiacSignId) -> str:
    if (sun, moon) in PAIR_TRAP:
        return PAIR_TRAP[(sun, moon)]
    tip = _ELEM_TIP.get((_ELEMENT[sun], _ELEMENT[moon]), "")
    sun_n = get_zodiac_by_id(sun).name_el
    moon_n = get_zodiac_by_id(moon).name_el
    return (
        f"Κοίτα το καθαρά: με Ήλιο στους/στον/στην {sun_n} κυνηγάς να {SUN_WANT[sun]}. "
        f"Με Σελήνη στους/στον/στην {moon_n}, όταν στρεσάρεσαι χρειάζεσαι {MOON_NEED[moon]}. "
        f"Το μπέρδεμα αρχίζει όταν κάνεις μόνο το ένα. {tip}"
    ).replace("στους/στον/στην ", "")


def build_rich_summary(
    sun_id: ZodiacSignId,
    moon_id: ZodiacSignId,
    asc_id: ZodiacSignId | None = None,
    name: str = "",
) -> str:
    sun = get_zodiac_by_id(sun_id)
    moon = get_zodiac_by_id(moon_id)
    who = name.strip() if name else "φίλε μου"

    opener = (
        f"### Άκου λίγο\n"
        f"**{who}**, θα σου το πω απλά, χωρίς αστρολογικά στρογγυλέματα. "
        f"Ο {sun_in_sign(sun_id)} δείχνει τι κυνηγάς στη ζωή: **{SUN_WANT[sun_id]}**. "
        f"Η {moon_in_sign(moon_id)} δείχνει τι χρειάζεσαι για να ηρεμήσεις: **{MOON_NEED[moon_id]}**. "
        f"Αυτά τα δύο πρέπει να συνεργάζονται — αλλιώς κουράζεσαι χωρίς να καταλαβαίνεις γιατί."
    )

    pattern = f"### Εκεί μπερδεύεσαι\n{_trap(sun_id, moon_id)}"

    example = (
        f"### Στην καθημερινότητα\n"
        f"{SUN_SCENE[sun_id]} "
        f"Αν εκείνη τη στιγμή αγνοήσεις τη Σελήνη ({moon.name_el}), "
        f"μένεις σφιγμένος ακόμα κι αν «κέρδισες» τη συζήτηση. "
        f"**Η πρακτική:** πρώτα φρόντισε αυτό που σε ηρεμεί ({MOON_NEED[moon_id]}), "
        f"και μετά κάνε μία καθαρή κίνηση προς αυτό που κυνηγάς ({SUN_WANT[sun_id]})."
    )

    if asc_id:
        face = (
            f"### Πώς σε βλέπουν\n"
            f"Ο {asc_in_sign(asc_id)} είναι η πρώτη εντύπωση: σε βλέπουν ως **{ASC_LOOK[asc_id]}**. "
            f"Πρόσεξε όμως — αυτό είναι η βιτρίνα. Μέσα σου παίζουν Ήλιος {sun.name_el} "
            f"και Σελήνη {moon.name_el}. "
            f"Γι’ αυτό μερικές φορές λες «δεν με καταλαβαίνουν». Δεν σε βλέπουν λάθος· "
            f"σε βλέπουν από έξω. Άσε λίγους να δουν και μέσα."
        )
    else:
        face = (
            "### Πώς σε βλέπουν\n"
            "Χωρίς ακριβή **ώρα γέννησης** δεν ανοίγει ο Ωροσκόπος — η πρώτη εντύπωση. "
            "Βάλε την αν μπορείς· τότε η ανάγνωση γίνεται πολύ πιο «εσύ»."
        )

    week = (
        f"### Τι να κάνεις αυτή την εβδομάδα\n"
        f"{WEEK[sun_id]} "
        f"Και για την ηρεμία σου: φρόντισε αυτό που ζητά η Σελήνη — {MOON_NEED[moon_id]}."
    )

    close = (
        f"### Κράτα αυτό\n"
        f"**{sun.name_el} σε κίνηση + {moon.name_el} σε φροντίδα = ισορροπία.** "
        f"Όχι το ένα αντί για το άλλο. Και μην περιμένεις να γίνεις άλλος άνθρωπος — "
        f"μάθε να δουλεύεις με αυτόν που ήδη είσαι."
    )

    return "\n\n".join([opener, pattern, example, face, week, close])
